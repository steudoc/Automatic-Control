H = 1/(s*(s+2)*(s+4));

%% 2)
%H = (-0.1*(1-2*s))/(s*(s+0.2)*(1+s));

%% 3)
%H = 1/((s^2)*(1+(s/3)));

%% 4)
%H = (2*(1+0.5*s))/((1+s)*(1-s)^2);

%% 5)
%H = (s^2 + 1)/((s-2)*(s+2)*(s+4));

%% 6)
%H = (0.125*(1+s^2))/(s*(1+0.25*s)*(1+0.5*s));

%% 7)
%H = (s-2)/((s+2)*(s^2 + 1));

%% 8)
%H = 0.25/(s*(1-0.5*s)^2);

%% 9)
%H = 1/((1+s^2)*(s+2));

%% 10)
%H = (-(1-s))/(s*(1+s^2));

%% 11)
%H = (s+1)/((s+2)*(5+4*s+s^2));

%% 12)
%H = ((s+3)*(2+2*s+s^2))/(s*(s-1)*(s+2)*(s+4));

%% 13)
%H = 1/(2*s^3);

%% 14)
%H = (s^3 + 4*s^2 + 7*s + 6) / (s^4 + 5*s^3 + 10*s^2 + 11*s + 3);

%% 15)
%H = (s^2 - 1) / (s^3 + s^2 + s -3);


